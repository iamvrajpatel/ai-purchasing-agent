ALLOWED_TRANSITIONS: dict[str, set[str]] = {
    "CREATED": {"INVESTIGATING", "FAILED"},
    "INVESTIGATING": {"DECIDED", "INVESTIGATION_REQUIRED", "FAILED"},
    "DECIDED": {"PROPOSED", "REJECTED", "INVESTIGATION_REQUIRED"},
    "PROPOSED": {"AWAITING_APPROVAL", "APPROVED", "EXECUTING"},
    "AWAITING_APPROVAL": {"APPROVED", "REJECTED"},
    "APPROVED": {"EXECUTING"},
    "EXECUTING": {"EXECUTED", "FAILED"},
    "EXECUTED": {"VALIDATING"},
    "VALIDATING": {"VALIDATED", "VALIDATION_FAILED"},
    "VALIDATION_FAILED": {"RECOVERING", "ESCALATED"},
    "RECOVERING": {"REVISED_PROPOSAL", "ESCALATED"},
}


def transition_allowed(current: str, target: str) -> bool:
    return target in ALLOWED_TRANSITIONS.get(current, set())

